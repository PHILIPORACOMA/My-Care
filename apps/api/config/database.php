|--------------------------------------------------------------------------
| MySQL 8 only — deliberately
|--------------------------------------------------------------------------
|
| The manuscript specifies MySQL 8.x (Table 29), and the project rule is that
| SQLite is never used, not even for tests: an in-memory SQLite run masks the
| suppression and aggregate bugs this system exists to avoid (UT-018, UT-020).
| Laravel's stock sqlite / mariadb / pgsql / sqlsrv connections have therefore
| been removed rather than left unused, so no configuration mistake or stray
| DB_CONNECTION value can silently fall back to a different engine.
|
| If a test run cannot reach MySQL, it must fail loudly. That is the point.
|
*/

